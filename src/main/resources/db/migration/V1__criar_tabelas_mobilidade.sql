CREATE SEQUENCE SEQ_EMPRESAS START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_USUARIOS START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_TIPOS_TRANSPORTE START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_DESLOCAMENTOS START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_RECOMPENSAS START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_RESGATES_RECOMPENSA START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE EMPRESAS (
    ID NUMBER(19) NOT NULL,
    NOME VARCHAR2(150) NOT NULL,
    CNPJ VARCHAR2(20) NOT NULL,
    SETOR VARCHAR2(100),
    PONTOS_SUSTENTAVEIS NUMBER(10) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_EMPRESAS PRIMARY KEY (ID),
    CONSTRAINT UK_EMPRESAS_CNPJ UNIQUE (CNPJ)
);

CREATE TABLE USUARIOS (
    ID NUMBER(19) NOT NULL,
    NOME VARCHAR2(150) NOT NULL,
    EMAIL VARCHAR2(150) NOT NULL,
    CPF VARCHAR2(14) NOT NULL,
    EMPRESA_ID NUMBER(19) NOT NULL,
    PONTOS_ACUMULADOS NUMBER(10) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_USUARIOS PRIMARY KEY (ID),
    CONSTRAINT UK_USUARIOS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT UK_USUARIOS_CPF UNIQUE (CPF),
    CONSTRAINT FK_USUARIOS_EMPRESAS FOREIGN KEY (EMPRESA_ID) REFERENCES EMPRESAS(ID)
);

CREATE TABLE TIPOS_TRANSPORTE (
    ID NUMBER(19) NOT NULL,
    NOME VARCHAR2(100) NOT NULL,
    SUSTENTAVEL NUMBER(1) NOT NULL,
    EMISSAO_CO2_KM NUMBER(10,4) NOT NULL,
    DESCRICAO VARCHAR2(255),
    CONSTRAINT PK_TIPOS_TRANSPORTE PRIMARY KEY (ID),
    CONSTRAINT CK_TIPOS_TRANSPORTE_SUST CHECK (SUSTENTAVEL IN (0, 1))
);

CREATE TABLE DESLOCAMENTOS (
    ID NUMBER(19) NOT NULL,
    USUARIO_ID NUMBER(19) NOT NULL,
    TIPO_TRANSPORTE_ID NUMBER(19) NOT NULL,
    DATA_DESLOCAMENTO DATE NOT NULL,
    DISTANCIA_KM NUMBER(10,2) NOT NULL,
    CO2_EVITADO_KG NUMBER(10,2),
    PONTOS_GERADOS NUMBER(10),
    CONSTRAINT PK_DESLOCAMENTOS PRIMARY KEY (ID),
    CONSTRAINT FK_DESLOC_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIOS(ID),
    CONSTRAINT FK_DESLOC_TRANSPORTE FOREIGN KEY (TIPO_TRANSPORTE_ID) REFERENCES TIPOS_TRANSPORTE(ID),
    CONSTRAINT CK_DESLOC_DISTANCIA CHECK (DISTANCIA_KM > 0)
);

CREATE TABLE RECOMPENSAS (
    ID NUMBER(19) NOT NULL,
    NOME VARCHAR2(120) NOT NULL,
    DESCRICAO VARCHAR2(255),
    PONTOS_NECESSARIOS NUMBER(10) NOT NULL,
    ATIVA NUMBER(1) NOT NULL,
    CONSTRAINT PK_RECOMPENSAS PRIMARY KEY (ID),
    CONSTRAINT CK_RECOMPENSAS_ATIVA CHECK (ATIVA IN (0, 1))
);

CREATE TABLE RESGATES_RECOMPENSA (
    ID NUMBER(19) NOT NULL,
    USUARIO_ID NUMBER(19) NOT NULL,
    RECOMPENSA_ID NUMBER(19) NOT NULL,
    DATA_RESGATE TIMESTAMP NOT NULL,
    STATUS VARCHAR2(30) NOT NULL,
    CONSTRAINT PK_RESGATES_RECOMPENSA PRIMARY KEY (ID),
    CONSTRAINT FK_RESGATES_USUARIOS FOREIGN KEY (USUARIO_ID) REFERENCES USUARIOS(ID),
    CONSTRAINT FK_RESGATES_RECOMPENSAS FOREIGN KEY (RECOMPENSA_ID) REFERENCES RECOMPENSAS(ID),
    CONSTRAINT CK_RESGATES_STATUS CHECK (STATUS IN ('SOLICITADO', 'APROVADO', 'CANCELADO'))
);
